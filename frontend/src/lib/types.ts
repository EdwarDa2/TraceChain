export type Role = 'OPERADOR' | 'ANALISTA_CALIDAD';
export type User = { id: string; name: string; email: string; role: Role };
export type Page<T> = { data: T[]; meta: { page: number; limit: number; total: number; totalPages: number } };
export type SyncStatus = 'PENDIENTE' | 'SINCRONIZADO' | 'ERROR';

export type Supplier = { id: string; code: string; name: string; active: boolean;
  contactName: string | null; email: string | null; phone: string | null; address: string | null };
export type Product = { id: string; code: string; name: string; type: string; unit: string;
  active: boolean; description: string | null };
export type Location = { id: string; code: string; name: string; type: string;
  active: boolean; address: string | null };
export type Lot = { id: string; code: string; productId: string; productName: string;
  productType: string; originType: string; initialQuantity: string; originAt: string;
  physicalQuantity: string; usableQuantity: string; unit: string; blocked: boolean;
  expired: boolean; exhausted: boolean; graphSyncStatus: SyncStatus };
export type Stock = { lotId: string; lotCode: string; productName: string; locationName: string;
  physicalQuantity: string; usableQuantity: string; unit: string; blocked: boolean;
  expired: boolean; updatedAt: string };
export type Movement = { id: string; lotId: string; type: string; direction: string;
  quantity: string; beforeQuantity: string; afterQuantity: string; movementAt: string };
export type TemplateParameter = { key: string; label: string; dataType: string; unit: string | null;
  required: boolean; options: string[]; min: string | null; max: string | null };
export type Template = { id: string; code: string; name: string; productId: string | null;
  version: number; parameters: TemplateParameter[] };
export type Inspection = { id: string; code: string; lotId: string; result: string;
  inspectedAt: string; findingsCount: number; parameters: Record<string, string | number | boolean> };
export type Finding = { type: string; parameter: string | null; description: string; severity: string };
export type Incident = { id: string; code: string; originLotId: string; title: string;
  type: string; severity: string; status: string; dossierStatus: SyncStatus;
  detectedAt: string; closedAt: string | null; resolution: string | null };
export type Block = { id: string; lotId: string; incidentId: string; reason: string;
  blockedAt: string; active: boolean; releasedAt: string | null };
export type DashboardSummary = { totalLots: number; totalProductions: number;
  activeIncidents: number; blockedLots: number };
export type Activity = { type: string; code: string; occurredAt: string; description: string };
export type SystemStatus = { status: string; sync: { destination: string; pending: number;
  processing: number; failed: number; completed: number; status: string }[] };
export type TraceResult = { status: string; queryType: string; summary: Record<string, number | null>;
  lots: { lotId: string; code: string; depth: number; direction: string }[];
  paths: { nodeIds: string[]; edgeIds: string[]; depth: number }[];
  destinations: { distributionCode: string; lotId: string; locationName: string }[];
  graph: { nodes: { id: string; label: string; type: string }[];
    edges: { id: string; source: string; target: string; type: string }[] };
  metadata: { warnings: { code: string; message: string }[]; durationMs: number } };
export type ImpactResult = { status: string; incident: Incident; summary: Record<string, number | null>;
  affectedLots: { lotId: string; code: string; depth: number; classification: string;
    physicalQuantity: string; usableQuantity: string; blocked: boolean }[];
  destinations: { data: { distributionCode: string; locationName: string;
    transferredQuantity: string }[] };
  quality: { status: string; data: { byLot: { lotId: string; nonConforming: number }[] } | null };
  graph: { nodes: { id: string; label: string; type: string }[];
    edges: { id: string; source: string; target: string; type: string }[] };
  metadata: { warnings: { code: string; message: string }[] } };
